// Fetches the gift certificate's fonts: TrueType subsets of every curated display font (400 and 600) and accent font
// (italic 400) into src/brand/certificate-fonts/, and writes the table src/brand/certificate-fonts.ts (size and sha256
// per file). Run `node scripts/fetch-font-files.mjs` after changing CURATED_FONTS. The network is limited to
// fonts.googleapis.com (the css2 list) and fonts.gstatic.com (the files). A plain user agent makes Google answer with
// TrueType; a browser would get woff2.
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "src/brand/certificate-fonts");
const tablePath = join(root, "src/brand/certificate-fonts.ts");

/** ASCII, Latin-1 and Latin Extended-A, and the typographic punctuation the certificate may show. */
export function certificateText() {
  let text = "";
  for (let c = 32; c <= 126; c += 1) text += String.fromCharCode(c);
  for (let c = 0xa0; c <= 0x17f; c += 1) text += String.fromCharCode(c);
  return text + "–—‘’“”•…€™";
}

/** The css2 address for one file. `kind` is "400", "600" or "italic". */
export function cssUrl(family, kind) {
  const name = encodeURIComponent(family).replace(/%20/g, "+");
  const axis = kind === "italic" ? "ital,wght@1,400" : `wght@${kind}`;
  return `https://fonts.googleapis.com/css2?family=${name}:${axis}&text=${encodeURIComponent(certificateText())}`;
}

/** The one https://fonts.gstatic.com address in a css2 answer, or null. */
export function fontUrlFrom(css) {
  const match = /url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)\s*format\('truetype'\)/.exec(css);
  return match ? match[1] : null;
}

/** True for a TrueType file: 00 01 00 00 or "true". */
export function isTrueType(bytes) {
  if (bytes.length < 4) return false;
  const tag = String.fromCharCode(bytes[0], bytes[1], bytes[2], bytes[3]);
  return tag === "\u0000\u0001\u0000\u0000" || tag === "true";
}

async function get(url, host) {
  if (new URL(url).host !== host) throw new Error(`Refusing ${url}: not ${host}.`);
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} answered ${response.status}.`);
  return response;
}

export async function main() {
  const { CURATED_FONTS } = await import(pathToFileURL(join(root, "src/brand/fonts.ts")).href);
  const jobs = [];
  for (const font of CURATED_FONTS.display) for (const kind of ["400", "600"]) jobs.push({ role: "display", font, kind });
  for (const font of CURATED_FONTS.accent) jobs.push({ role: "accent", font, kind: "italic" });
  mkdirSync(outDir, { recursive: true });
  for (const name of readdirSync(outDir)) if (name.endsWith(".ttf")) rmSync(join(outDir, name));
  const table = {};
  for (const { role, font, kind } of jobs) {
    const css = await (await get(cssUrl(font.family, kind), "fonts.googleapis.com")).text();
    const url = fontUrlFrom(css);
    if (url === null) throw new Error(`No TrueType file in the answer for ${font.family} ${kind}.`);
    const bytes = new Uint8Array(await (await get(url, "fonts.gstatic.com")).arrayBuffer());
    if (!isTrueType(bytes)) throw new Error(`${font.family} ${kind} is not a TrueType file.`);
    const file = `${role}-${font.id}-${kind}.ttf`;
    writeFileSync(join(outDir, file), bytes);
    table[file] = { bytes: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex") };
    console.log(`${file} ${bytes.length}`);
  }
  const rows = Object.entries(table)
    .map(([file, v]) => `  "${file}": { bytes: ${v.bytes}, sha256: "${v.sha256}" },`)
    .join("\n");
  writeFileSync(
    tablePath,
    `// Generated by scripts/fetch-font-files.mjs; do not edit by hand. The gift certificate's TrueType subsets (ASCII, Latin-1,
// Latin Extended-A and typographic punctuation), one file per curated display font (400, 600) and accent font
// (italic 400). Import-free. src/brand/certificate-fonts.test.ts checks the folder against this table.
export const CERTIFICATE_FONT_FILES: Record<string, { bytes: number; sha256: string }> = {
${rows}
};
`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
