import assert from "node:assert/strict";
import { test } from "node:test";
import { isWoff2, parseGoogleCss, tableModule } from "./fetch-font-files.mjs";

const CSS = `/* vietnamese */
@font-face {
  font-family: 'Newsreader';
  font-style: italic;
  font-weight: 400;
  font-display: swap;
  src: url(https://fonts.gstatic.com/s/newsreader/v1/a.woff2) format('woff2');
  unicode-range: U+0102-0103, U+1EA0-1EF9;
}
/* latin */
@font-face {
  font-family: 'Newsreader';
  font-style: italic;
  font-weight: 400;
  font-display: swap;
  src: url(https://fonts.gstatic.com/s/newsreader/v1/b.woff2) format('woff2');
  unicode-range: U+0000-00FF, U+2000-206F;
}
`;

test("parseGoogleCss keeps every subset in Google's order with its file and range", () => {
  assert.deepEqual(parseGoogleCss(CSS), [
    { subset: "vietnamese", url: "https://fonts.gstatic.com/s/newsreader/v1/a.woff2", unicodeRange: "U+0102-0103, U+1EA0-1EF9" },
    { subset: "latin", url: "https://fonts.gstatic.com/s/newsreader/v1/b.woff2", unicodeRange: "U+0000-00FF, U+2000-206F" },
  ]);
});

test("parseGoogleCss refuses an answer with no faces or a face without a woff2 file", () => {
  assert.throws(() => parseGoogleCss("<html>quota</html>"), /no @font-face/);
  assert.throws(() => parseGoogleCss("/* latin */ @font-face { src: url(https://x/a.ttf) format('truetype'); unicode-range: U+0; }"), /Unexpected/);
});

test("tableModule writes a typed, import-free module", () => {
  const out = tableModule({ "accent-x": { request: "https://fonts.googleapis.com/css2?family=X", faces: [] } });
  assert.match(out, /^\/\/ Generated by `node scripts\/fetch-font-files\.mjs`/);
  assert.match(out, /export const FONT_FILES: Record<string, FontFileEntry> = \{\n  "accent-x": \{/);
  assert.doesNotMatch(out, /^import /m);
});

test("parseGoogleCss takes files from fonts.gstatic.com only, and ranges in Google's form only", () => {
  assert.throws(() => parseGoogleCss(CSS.replace("https://fonts.gstatic.com", "https://evil.example")), /Unexpected/);
  assert.throws(() => parseGoogleCss(CSS.replace("U+0000-00FF", 'U+0000-00FF" }); evil(); ("')), /Unexpected/);
});

test("isWoff2 checks the signature", () => {
  assert.equal(isWoff2(Buffer.from("wOF2xxxx")), true);
  assert.equal(isWoff2(Buffer.from("<html>")), false);
});
